# Machine Learning Model Code

This folder contains the MATLAB implementations and supporting scripts used throughout the liver cirrhosis machine learning project.

Included code covers:
- Decision Tree models
- Random Forest models
- Multilayer Perceptron (MLP) neural networks
- Convolutional Neural Network (CNN) workflows
- Dataset preprocessing and feature engineering utilities

Some models were implemented using MATLAB built-in machine learning functions, while others were developed partially or fully from scratch for educational and comparative analysis purposes.

Refer to the project report and website documentation for additional implementation details, preprocessing methodology, and performance analysis.
